#!/usr/bin/env bash
# 30 — GPU: detect GPUs and write a machine-local Hyprland GPU file
# (~/.config/devy/local/gpu.lua) plus the system bits each GPU needs.
#
# VM and Intel paths are the M1 target. The NVIDIA hybrid path is M2 work and is
# marked UNTESTED until verified on the HP Victus (see docs/UNVERIFIED.md).

log_step "GPU setup"

local_dir="$DEVY_CONFIG_HOME/devy/local"
run mkdir -p "$local_dir"
gpu_lua="$local_dir/gpu.lua"

# Collect "<pci-address> <vendor-id>" for every DRM card (cards, not render nodes).
declare -A gpu_by_vendor=()
for card in /sys/class/drm/card[0-9]*; do
  [[ -e $card/device/vendor ]] || continue
  [[ $(basename "$card") == *-* ]] && continue # skip connectors like card1-eDP-1
  vendor="$(cat "$card/device/vendor")"
  addr="$(basename "$(readlink -f "$card/device")")"
  gpu_by_vendor[$vendor]="$addr"
done

has_intel=0 has_nvidia=0 has_amd=0
[[ -n ${gpu_by_vendor[0x8086]:-} ]] && has_intel=1
[[ -n ${gpu_by_vendor[0x10de]:-} ]] && has_nvidia=1
[[ -n ${gpu_by_vendor[0x1002]:-} ]] && has_amd=1
log_info "detected: intel=$has_intel nvidia=$has_nvidia amd=$has_amd (profile $DEVY_PROFILE)"

write_gpu_lua() {
  if [[ $DEVY_DRY_RUN == 1 ]]; then
    log_info "[dry-run] would write $gpu_lua:"
    sed 's/^/      /'
  else
    cat >"$gpu_lua"
    log_ok "wrote $gpu_lua"
  fi
}

if [[ $DEVY_PROFILE == vm ]]; then
  # In a VM (virtio-gpu or llvmpipe) blur/shadows/animations cost a lot of CPU.
  write_gpu_lua <<'EOF'
-- Generated by Devy install/30-gpu.sh — profile: vm. Re-run install.sh to regenerate.
hl.config({
  decoration = { blur = { enabled = false }, shadow = { enabled = false } },
  animations = { enabled = false },
})
EOF

elif [[ $has_intel == 1 && $has_nvidia == 1 ]]; then
  # UNTESTED (M2): hybrid Intel iGPU + NVIDIA dGPU.
  # Plan (Hyprland wiki: Multi-GPU + Nvidia): the iGPU drives the desktop, NVIDIA is
  # used per-app via `prime-run`. Stable /dev/dri/* names come from udev symlinks,
  # because cardN numbering changes between boots and ':' in by-path names breaks
  # AQ_DRM_DEVICES.
  igpu="${gpu_by_vendor[0x8086]}"
  dgpu="${gpu_by_vendor[0x10de]}"
  write_root_file /etc/udev/rules.d/70-devy-gpu-paths.rules <<EOF
# Devy: stable names for Hyprland's AQ_DRM_DEVICES (generated by install/30-gpu.sh)
KERNEL=="card*", KERNELS=="$igpu", SUBSYSTEM=="drm", SUBSYSTEMS=="pci", SYMLINK+="dri/devy-igpu"
KERNEL=="card*", KERNELS=="$dgpu", SUBSYSTEM=="drm", SUBSYSTEMS=="pci", SYMLINK+="dri/devy-dgpu"
EOF
  # Suspend/resume helpers shipped by nvidia-utils (Hyprland wiki: Nvidia).
  enable_unit nvidia-suspend.service nvidia-hibernate.service nvidia-resume.service

  write_gpu_lua <<'EOF'
-- Generated by Devy install/30-gpu.sh — hybrid Intel + NVIDIA. UNTESTED (M2).
-- iGPU first: renders the desktop and saves battery. dGPU listed so monitors wired
-- to it (HDMI on many laptops) still work.
hl.env("AQ_DRM_DEVICES", "/dev/dri/devy-igpu:/dev/dri/devy-dgpu")
-- nvidia-vaapi-driver backend; only matters for apps that pick the NVIDIA VA-API.
hl.env("NVD_BACKEND", "direct")
-- Do NOT set LIBVA_DRIVER_NAME/__GLX_VENDOR_LIBRARY_NAME globally on hybrid laptops:
-- it breaks Chromium video when the iGPU drives the display. Use `prime-run app`.
EOF

elif [[ $has_nvidia == 1 ]]; then
  # UNTESTED: NVIDIA-only desktop.
  enable_unit nvidia-suspend.service nvidia-hibernate.service nvidia-resume.service
  write_gpu_lua <<'EOF'
-- Generated by Devy install/30-gpu.sh — NVIDIA only. UNTESTED.
hl.env("LIBVA_DRIVER_NAME", "nvidia")
hl.env("__GLX_VENDOR_LIBRARY_NAME", "nvidia")
hl.env("NVD_BACKEND", "direct")
EOF

else
  write_gpu_lua <<'EOF'
-- Generated by Devy install/30-gpu.sh — Intel/AMD (Mesa). Nothing special needed.
EOF
fi
